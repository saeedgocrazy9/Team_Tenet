/**
 * Kayda Sathi — Triage Result Screen
 * Displays the complete legal action kit with 3 tabs:
 * 1. Action Roadmap (escalation timeline)
 * 2. Evidence Checklist (with case strength meter)
 * 3. Legal Notice (editable + PDF export + WhatsApp share)
 */

import React, { useState, useMemo, useCallback } from 'react';
import {
  StyleSheet,
  View,
  Pressable,
  ScrollView,
  Alert,
  Linking,
  Platform,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useRouter } from 'expo-router';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import Animated, {
  FadeInDown,
  FadeIn,
  SlideInRight,
} from 'react-native-reanimated';

import { ThemedText } from '@/components/themed-text';
import { ThemedView } from '@/components/themed-view';
import { Spacing, BorderRadius, FontSizes, CategoryConfig, Colors } from '@/constants/theme';
import { useTheme } from '@/hooks/use-theme';
import type { TriageResponse, AppTab, CheckedDocuments } from '@/types/triage';

// ── Get triage result from global state ───────────────────────────────────
function getTriageResult(): TriageResponse | null {
  return ((global as Record<string, unknown>).__triageResult as TriageResponse) ?? null;
}

// ── Tab definitions ───────────────────────────────────────────────────────
const TABS: { key: AppTab; label: string; icon: string }[] = [
  { key: 'roadmap', label: 'Roadmap', icon: '🗺️' },
  { key: 'checklist', label: 'Evidence', icon: '📋' },
  { key: 'notice', label: 'Notice', icon: '📄' },
];

export default function ResultScreen() {
  const theme = useTheme();
  const router = useRouter();
  const data = getTriageResult();
  const [activeTab, setActiveTab] = useState<AppTab>('roadmap');
  const [checkedDocs, setCheckedDocs] = useState<CheckedDocuments>({});
  const [noticeText, setNoticeText] = useState(data?.legal_notice ?? '');

  if (!data) {
    return (
      <ThemedView style={styles.container}>
        <SafeAreaView style={styles.emptyContainer}>
          <ThemedText style={{ fontSize: 48 }}>🤷</ThemedText>
          <ThemedText style={[styles.emptyTitle, { color: theme.text }]}>
            No results yet
          </ThemedText>
          <Pressable onPress={() => router.back()} style={[styles.backButton, { backgroundColor: theme.primary }]}>
            <ThemedText style={{ color: '#FFF', fontWeight: '700' }}>← Go Back</ThemedText>
          </Pressable>
        </SafeAreaView>
      </ThemedView>
    );
  }

  // ── Computed case strength based on checked documents ────────────────
  const computedStrength = useMemo(() => {
    const totalWeight = data.document_checklist.reduce((sum, d) => sum + d.weight, 0);
    const checkedWeight = data.document_checklist
      .filter((d) => checkedDocs[d.name])
      .reduce((sum, d) => sum + d.weight, 0);

    const ratio = totalWeight > 0 ? checkedWeight / totalWeight : 0;
    const score = Math.round(data.case_strength.score * ratio);

    let label: string;
    if (score >= 80) label = 'Very Strong';
    else if (score >= 60) label = 'Strong';
    else if (score >= 40) label = 'Moderate';
    else if (score >= 20) label = 'Weak';
    else label = 'Very Weak';

    return { score, label };
  }, [checkedDocs, data]);

  const strengthColor =
    computedStrength.score >= 60
      ? theme.strengthHigh
      : computedStrength.score >= 35
        ? theme.strengthMid
        : theme.strengthLow;

  // ── Document toggle ─────────────────────────────────────────────────
  const toggleDoc = useCallback((name: string) => {
    setCheckedDocs((prev) => ({ ...prev, [name]: !prev[name] }));
  }, []);

  // ── PDF Export ──────────────────────────────────────────────────────
  const exportPDF = useCallback(async () => {
    try {
      const html = `
        <html>
          <head>
            <meta charset="utf-8" />
            <style>
              body { font-family: 'Georgia', serif; padding: 40px; color: #1a1a1a; line-height: 1.8; }
              h1 { text-align: center; color: #B45309; border-bottom: 2px solid #B45309; padding-bottom: 10px; }
              h2 { color: #1E40AF; margin-top: 24px; }
              .header { text-align: center; margin-bottom: 30px; }
              .notice { white-space: pre-wrap; font-size: 14px; }
              .footer { margin-top: 40px; font-size: 11px; color: #666; text-align: center; border-top: 1px solid #ddd; padding-top: 10px; }
            </style>
          </head>
          <body>
            <div class="header">
              <h1>⚖️ LEGAL DEMAND NOTICE</h1>
              <p><strong>Category:</strong> ${data.category}</p>
              <p><strong>Generated by Kayda Sathi</strong></p>
            </div>
            <div class="notice">${noticeText.replace(/\n/g, '<br/>')}</div>
            <div class="footer">
              <p>This notice was generated using Kayda Sathi — Legal First-Aid Kit for Indian Citizens.</p>
              <p>This is legal information, not legal advice. Consult a practicing advocate for complex matters.</p>
            </div>
          </body>
        </html>
      `;

      const { uri } = await Print.printToFileAsync({ html, base64: false });

      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(uri, {
          mimeType: 'application/pdf',
          dialogTitle: 'Share Legal Notice',
          UTI: 'com.adobe.pdf',
        });
      } else {
        Alert.alert('PDF Saved', `Notice saved to: ${uri}`);
      }
    } catch (err) {
      console.error('PDF export failed:', err);
      Alert.alert('Error', 'Failed to export PDF. Please try again.');
    }
  }, [noticeText, data]);

  // ── WhatsApp Share ──────────────────────────────────────────────────
  const shareWhatsApp = useCallback(async () => {
    const message = encodeURIComponent(noticeText);
    const url = `whatsapp://send?text=${message}`;

    try {
      const supported = await Linking.canOpenURL(url);
      if (supported) {
        await Linking.openURL(url);
      } else {
        Alert.alert('WhatsApp not found', 'Please install WhatsApp to use this feature.');
      }
    } catch (err) {
      Alert.alert('Error', 'Could not open WhatsApp.');
    }
  }, [noticeText]);

  // ── Category config ─────────────────────────────────────────────────
  const catConfig = CategoryConfig[data.category] ?? { icon: '⚖️', color: 'primary' };
  const catColor = theme[catConfig.color as keyof typeof theme] as string;

  // ── Follow-up date ──────────────────────────────────────────────────
  const followUpDate = useMemo(() => {
    const now = new Date();
    now.setDate(now.getDate() + data.follow_up.grace_period_days);
    return now.toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' });
  }, [data]);

  return (
    <ThemedView style={styles.container}>
      <SafeAreaView style={styles.safeArea}>
        {/* Top Bar */}
        <View style={styles.topBar}>
          <Pressable onPress={() => router.back()} style={styles.backBtn}>
            <ThemedText style={{ color: theme.primary, fontSize: 16, fontWeight: '700' }}>← Back</ThemedText>
          </Pressable>
          <ThemedText style={[styles.topBarTitle, { color: theme.text }]}>Results</ThemedText>
          <View style={{ width: 60 }} />
        </View>

        {/* Category Badge + Limitation Clock */}
        <Animated.View entering={FadeInDown.duration(400)}>
          <View style={styles.badgeRow}>
            <View style={[styles.categoryBadge, { backgroundColor: catColor + '22', borderColor: catColor }]}>
              <ThemedText style={{ fontSize: 16 }}>{catConfig.icon}</ThemedText>
              <ThemedText style={[styles.categoryText, { color: catColor }]}>
                {data.category}
              </ThemedText>
            </View>
            <View style={[styles.limitBadge, { backgroundColor: theme.dangerLight, borderColor: theme.danger }]}>
              <ThemedText style={{ fontSize: 14 }}>⏰</ThemedText>
              <ThemedText style={[styles.limitText, { color: theme.danger }]}>
                {data.limitation_days} days left
              </ThemedText>
            </View>
          </View>
        </Animated.View>

        {/* Summary */}
        <Animated.View entering={FadeInDown.duration(400).delay(100)}>
          <View style={[styles.summaryCard, { backgroundColor: theme.card, borderColor: theme.border }]}>
            <ThemedText style={[styles.summaryText, { color: theme.text }]}>
              {data.summary}
            </ThemedText>
          </View>
        </Animated.View>

        {/* Tab Switcher */}
        <View style={[styles.tabRow, { backgroundColor: theme.backgroundElement, borderColor: theme.border }]}>
          {TABS.map((tab) => (
            <Pressable
              key={tab.key}
              onPress={() => setActiveTab(tab.key)}
              style={[
                styles.tab,
                activeTab === tab.key && { backgroundColor: theme.primary },
              ]}
            >
              <ThemedText style={{ fontSize: 14 }}>{tab.icon}</ThemedText>
              <ThemedText
                style={[
                  styles.tabText,
                  { color: activeTab === tab.key ? '#FFF' : theme.textSecondary },
                ]}
              >
                {tab.label}
              </ThemedText>
            </Pressable>
          ))}
        </View>

        {/* Tab Content */}
        <ScrollView style={styles.tabContent} showsVerticalScrollIndicator={false}>
          {activeTab === 'roadmap' && (
            <Animated.View entering={FadeIn.duration(300)}>
              {/* Statutes */}
              <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary }]}>
                📚 APPLICABLE LAWS
              </ThemedText>
              {data.statutes.map((s, i) => (
                <Animated.View key={i} entering={SlideInRight.duration(300).delay(i * 80)}>
                  <View style={[styles.statuteCard, { backgroundColor: theme.card, borderColor: theme.border }]}>
                    <ThemedText style={[styles.statuteName, { color: theme.accent }]}>
                      {s.act_name}
                    </ThemedText>
                    <ThemedText style={[styles.statuteSection, { color: theme.primary }]}>
                      {s.section}
                    </ThemedText>
                    <ThemedText style={[styles.statuteRelevance, { color: theme.textSecondary }]}>
                      {s.relevance}
                    </ThemedText>
                  </View>
                </Animated.View>
              ))}

              {/* Action Steps */}
              <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary }]}>
                🗺️ ACTION ROADMAP
              </ThemedText>
              {data.action_steps.map((step, i) => {
                const levelColor =
                  step.escalation_level === 'Informal'
                    ? theme.success
                    : step.escalation_level === 'Pre-Litigation'
                      ? theme.warning
                      : theme.danger;
                return (
                  <Animated.View key={i} entering={SlideInRight.duration(300).delay(i * 100)}>
                    <View style={styles.stepRow}>
                      {/* Timeline line */}
                      <View style={styles.stepTimeline}>
                        <View style={[styles.stepDot, { backgroundColor: levelColor }]}>
                          <ThemedText style={styles.stepNum}>{step.step_number}</ThemedText>
                        </View>
                        {i < data.action_steps.length - 1 && (
                          <View style={[styles.stepLine, { backgroundColor: theme.border }]} />
                        )}
                      </View>
                      {/* Content */}
                      <View style={[styles.stepCard, { backgroundColor: theme.card, borderColor: theme.border }]}>
                        <View style={styles.stepHeader}>
                          <ThemedText style={[styles.stepTitle, { color: theme.text }]}>
                            {step.title}
                          </ThemedText>
                          <View style={[styles.levelBadge, { backgroundColor: levelColor + '22' }]}>
                            <ThemedText style={[styles.levelText, { color: levelColor }]}>
                              {step.escalation_level}
                            </ThemedText>
                          </View>
                        </View>
                        <ThemedText style={[styles.stepDesc, { color: theme.textSecondary }]}>
                          {step.description}
                        </ThemedText>
                        <ThemedText style={[styles.stepTimelabel, { color: theme.primary }]}>
                          ⏱ {step.timeline}
                        </ThemedText>
                      </View>
                    </View>
                  </Animated.View>
                );
              })}

              {/* Authority */}
              <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary }]}>
                🏛️ WHERE TO GO
              </ThemedText>
              <View style={[styles.authorityCard, { backgroundColor: theme.accentLight, borderColor: theme.accent }]}>
                <ThemedText style={{ fontSize: 28 }}>🏛️</ThemedText>
                <ThemedText style={[styles.authorityName, { color: theme.accent }]}>
                  {data.authority.forum_name}
                </ThemedText>
                <View style={[styles.authorityTypeBadge, { backgroundColor: theme.accent + '22' }]}>
                  <ThemedText style={[styles.authorityType, { color: theme.accent }]}>
                    {data.authority.forum_type}
                  </ThemedText>
                </View>
                <ThemedText style={[styles.authorityDesc, { color: theme.textSecondary }]}>
                  {data.authority.description}
                </ThemedText>
                {data.authority.jurisdiction_note && (
                  <ThemedText style={[styles.jurisdictionNote, { color: theme.textSecondary }]}>
                    📍 {data.authority.jurisdiction_note}
                  </ThemedText>
                )}
              </View>

              {/* Follow-up Reminder */}
              <View style={[styles.followUpCard, { backgroundColor: theme.warningLight, borderColor: theme.warning }]}>
                <ThemedText style={{ fontSize: 20 }}>🔔</ThemedText>
                <View style={{ flex: 1 }}>
                  <ThemedText style={[styles.followUpTitle, { color: theme.warning }]}>
                    Follow-up Reminder
                  </ThemedText>
                  <ThemedText style={[styles.followUpText, { color: theme.textSecondary }]}>
                    {data.follow_up.reminder_text}
                  </ThemedText>
                  <ThemedText style={[styles.followUpDate, { color: theme.warning }]}>
                    📅 Grace period ends: {followUpDate}
                  </ThemedText>
                </View>
              </View>

              {/* Limitation Note */}
              <View style={[styles.limitNoteCard, { backgroundColor: theme.dangerLight, borderColor: theme.danger }]}>
                <ThemedText style={{ fontSize: 16 }}>⚠️</ThemedText>
                <ThemedText style={[styles.limitNoteText, { color: theme.danger }]}>
                  {data.limitation_note}
                </ThemedText>
              </View>
            </Animated.View>
          )}

          {activeTab === 'checklist' && (
            <Animated.View entering={FadeIn.duration(300)}>
              {/* Case Strength Meter */}
              <View style={[styles.strengthCard, { backgroundColor: theme.card, borderColor: theme.border }]}>
                <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary, marginTop: 0 }]}>
                  💪 CASE STRENGTH
                </ThemedText>
                <View style={styles.strengthGauge}>
                  <View style={styles.strengthCircle}>
                    <View
                      style={[
                        styles.strengthInner,
                        { borderColor: strengthColor, backgroundColor: strengthColor + '15' },
                      ]}
                    >
                      <ThemedText style={[styles.strengthScore, { color: strengthColor }]}>
                        {checkedDocs && Object.keys(checkedDocs).some((k) => checkedDocs[k])
                          ? computedStrength.score
                          : '—'}
                      </ThemedText>
                      <ThemedText style={[styles.strengthLabel, { color: strengthColor }]}>
                        {checkedDocs && Object.keys(checkedDocs).some((k) => checkedDocs[k])
                          ? computedStrength.label
                          : 'Check docs'}
                      </ThemedText>
                    </View>
                  </View>
                  <ThemedText style={[styles.strengthExplain, { color: theme.textSecondary }]}>
                    {data.case_strength.explanation}
                  </ThemedText>
                  <ThemedText style={[styles.strengthHint, { color: theme.textSecondary }]}>
                    Check the documents you have below to calculate your score
                  </ThemedText>
                </View>
              </View>

              {/* Document Checklist */}
              <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary }]}>
                📋 EVIDENCE CHECKLIST
              </ThemedText>
              {data.document_checklist.map((doc, i) => (
                <Animated.View key={i} entering={SlideInRight.duration(300).delay(i * 80)}>
                  <Pressable
                    onPress={() => toggleDoc(doc.name)}
                    style={[
                      styles.docItem,
                      {
                        backgroundColor: checkedDocs[doc.name] ? theme.successLight : theme.card,
                        borderColor: checkedDocs[doc.name] ? theme.success : theme.border,
                      },
                    ]}
                  >
                    <View style={[
                      styles.checkbox,
                      {
                        borderColor: checkedDocs[doc.name] ? theme.success : theme.border,
                        backgroundColor: checkedDocs[doc.name] ? theme.success : 'transparent',
                      },
                    ]}>
                      {checkedDocs[doc.name] && (
                        <ThemedText style={{ color: '#FFF', fontSize: 12, fontWeight: '700' }}>✓</ThemedText>
                      )}
                    </View>
                    <View style={{ flex: 1 }}>
                      <View style={styles.docHeader}>
                        <ThemedText style={[styles.docName, { color: theme.text }]}>
                          {doc.name}
                        </ThemedText>
                        {doc.is_critical && (
                          <View style={[styles.criticalBadge, { backgroundColor: theme.dangerLight }]}>
                            <ThemedText style={{ color: theme.danger, fontSize: 10, fontWeight: '700' }}>
                              CRITICAL
                            </ThemedText>
                          </View>
                        )}
                      </View>
                      <ThemedText style={[styles.docDesc, { color: theme.textSecondary }]}>
                        {doc.description}
                      </ThemedText>
                      <View style={styles.docWeightRow}>
                        <View style={[styles.weightBar, { backgroundColor: theme.backgroundElement }]}>
                          <View
                            style={[
                              styles.weightFill,
                              { width: `${doc.weight}%`, backgroundColor: theme.primary },
                            ]}
                          />
                        </View>
                        <ThemedText style={[styles.weightText, { color: theme.textSecondary }]}>
                          +{doc.weight}%
                        </ThemedText>
                      </View>
                    </View>
                  </Pressable>
                </Animated.View>
              ))}
            </Animated.View>
          )}

          {activeTab === 'notice' && (
            <Animated.View entering={FadeIn.duration(300)}>
              {/* Notice Preview */}
              <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary }]}>
                📄 LEGAL DEMAND NOTICE
              </ThemedText>
              <View style={[styles.noticeCard, { backgroundColor: theme.card, borderColor: theme.border }]}>
                <ScrollView
                  nestedScrollEnabled
                  style={styles.noticeScroll}
                >
                  <ThemedText
                    style={[styles.noticeText, { color: theme.text }]}
                    selectable
                  >
                    {noticeText}
                  </ThemedText>
                </ScrollView>
              </View>

              {/* Action Buttons */}
              <View style={styles.noticeActions}>
                <Pressable
                  onPress={exportPDF}
                  style={[styles.actionBtn, { backgroundColor: theme.primary }]}
                >
                  <ThemedText style={styles.actionBtnText}>📄 Export PDF</ThemedText>
                </Pressable>
                <Pressable
                  onPress={shareWhatsApp}
                  style={[styles.actionBtn, { backgroundColor: '#25D366' }]}
                >
                  <ThemedText style={styles.actionBtnText}>💬 WhatsApp</ThemedText>
                </Pressable>
              </View>

              {/* Entities extracted */}
              <ThemedText style={[styles.sectionHeader, { color: theme.textSecondary }]}>
                📝 EXTRACTED DETAILS
              </ThemedText>
              <View style={[styles.entityCard, { backgroundColor: theme.card, borderColor: theme.border }]}>
                {data.entities.opponent_name && (
                  <EntityRow label="Opponent" value={data.entities.opponent_name} theme={theme} />
                )}
                {data.entities.amount && (
                  <EntityRow label="Amount" value={data.entities.amount} theme={theme} />
                )}
                {data.entities.location && (
                  <EntityRow label="Location" value={data.entities.location} theme={theme} />
                )}
                {data.entities.duration && (
                  <EntityRow label="Duration" value={data.entities.duration} theme={theme} />
                )}
                {data.entities.date_of_incident && (
                  <EntityRow label="Date" value={data.entities.date_of_incident} theme={theme} />
                )}
              </View>
            </Animated.View>
          )}

          <View style={{ height: 120 }} />
        </ScrollView>
      </SafeAreaView>
    </ThemedView>
  );
}

// ── Entity Row Component ────────────────────────────────────────────────────
function EntityRow({ label, value, theme }: { label: string; value: string; theme: Record<string, string> }) {
  return (
    <View style={entityStyles.row}>
      <ThemedText style={[entityStyles.label, { color: theme.textSecondary }]}>{label}</ThemedText>
      <ThemedText style={[entityStyles.value, { color: theme.text }]}>{value}</ThemedText>
    </View>
  );
}

